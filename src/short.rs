#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shim_names_and_targets() {
        assert_eq!(SHIMS.len(), 5);
        let subs: Vec<&str> = SHIMS.iter().map(|(_, s)| *s).collect();
        assert_eq!(subs, vec!["path", "env", "link", "http", "ai"]);
        let names: Vec<&str> = SHIMS.iter().map(|(n, _)| *n).collect();
        assert_eq!(names, vec!["spath", "senv", "slink", "shttp", "sai"]);
    }

    #[cfg(windows)]
    #[test]
    fn windows_shim_content() {
        let c = shim_content(Path::new(r"C:\tools\sysenv.exe"), "path");
        assert!(c.starts_with("@echo off\r\n"));
        assert!(c.contains(r#""C:\tools\sysenv.exe" path %*"#));
    }

    #[cfg(not(windows))]
    #[test]
    fn unix_shim_content() {
        let c = shim_content(Path::new("/opt/sysenv"), "env");
        assert!(c.starts_with("#!/bin/sh\n"));
        assert!(c.contains(r#"exec "/opt/sysenv" env "$@""#));
    }
}
